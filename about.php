      <h1>• Origem da Ilha do Sal •</h1>
<p>
    A Ilha do Sal foi formada a partir da atividade vulcânica submarina e da atividade tectónica há milhões de anos.
    Os vulcões submarinos entraram em erupção, a lava arrefeceu e acabou por formar camadas de rocha vulcânica.
    Com o tempo, essas camadas de rocha emergiram do oceano e uniram-se para formar a ilha, criando uma geologia única no planeta.
</p>

<p>
    Esta ilha é um dos principais destinos turísticos de Cabo Verde e está localizada no arquipélago das Ilhas Barlavento.
    É a mais pequena ilha do país, com uma área de aproximadamente 216 km², mas apesar do seu tamanho, tem uma história rica,
    uma fauna e flora variadas e uma água do mar turquesa de temperatura agradável que a tornam um destino único para visitantes de todo o mundo.
</p>


